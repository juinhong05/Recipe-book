"""Publish only reviewed recipes; recalculate editorial nutrition from saved USDA facts."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
recipes = json.loads((ROOT / 'scripts/reviewed-recipes.json').read_text(encoding='utf-8'))
profiles = json.loads((ROOT / 'scripts/nutrition-profiles.json').read_text(encoding='utf-8'))['foods']
for recipe in recipes:
    if recipe['nutritionKind'] == 'calculated':
        totals = {key: sum(profiles[item['profile']][key] * item['grams'] / 100
                           for item in recipe['nutritionComponents']) / recipe['servings']
                  for key in ('kcal', 'protein')}
        recipe['kcal'] = math.floor(totals['kcal'] / 10 + 0.5) * 10
        recipe['protein'] = math.floor(totals['protein'] + 0.5)
    assert all(isinstance(recipe[key], (int, float)) and recipe[key] > 0
               for key in ('servings', 'kcal', 'protein'))
    assert all(isinstance(recipe[key], (int, float)) and recipe[key] >= 0
               for key in ('prep', 'cook'))
    assert recipe['photoReviewed'] and recipe['photoKind'] == 'food-photograph'
    assert (ROOT / 'dist' / recipe['image'].removeprefix('./')).is_file()
    # Calculation workings stay in source control, not in the browser download.
    recipe.pop('nutritionComponents', None)
(ROOT / 'dist/catalogue.js').write_text(
    '// Generated by scripts/build-catalogue.py; edit scripts/reviewed-recipes.json.\n'
    + 'export const communityRecipes = ' + json.dumps(recipes, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8')
print(f'Built {len(recipes)} reviewed recipes ({sum(r["easy"] for r in recipes)} easy).')
